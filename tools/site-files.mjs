// Writing the built calendar to `data/` and `calendar/`.
//
// Kept apart from `pipeline.mjs` on purpose: that module runs inside the Neon
// refresh Function, where there is no writable project directory, so it must
// stay free of filesystem calls. This is the only place that touches them.
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";

export async function writeSiteFiles(root, payload, files) {
  const dataDir = path.join(root, "data");
  const calDir = path.join(root, "calendar");
  await mkdir(dataDir, { recursive: true });
  await mkdir(calDir, { recursive: true });

  await writeFile(path.join(dataDir, "calendar.json"), JSON.stringify(payload, null, 2));
  await writeFile(
    path.join(dataDir, "calendar.js"),
    `// Generated by \`npm run refresh\` at ${payload.generatedAt}\n` +
      `window.CALENDAR_DATA = ${JSON.stringify(payload)};\n`
  );

  for (const f of files) {
    await writeFile(path.join(calDir, f.file), f.content);
  }
}
